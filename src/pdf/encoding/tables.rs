pub(super) fn standard_byte_to_str(b: u8) -> Option<&'static str> {
    match b {
        0x27 => Some("’"),
        0x60 => Some("‘"),
        0x20..=0x7E => None,
        0xA1..=0xFF => adobe_standard_high_to_str(b as u32),
        _ => None,
    }
    .or_else(|| {
        if (0x20..=0x7E).contains(&b) {
            ASCII_SINGLE_STRS.get((b - 0x20) as usize).copied()
        } else {
            None
        }
    })
}

